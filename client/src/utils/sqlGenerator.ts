import { DiagramNode, DiagramEdge } from '../types';

export type SqlDialect = 'postgres' | 'mysql' | 'sqlite' | 'oracle';

function quoteIdentifier(id: string, dialect: SqlDialect): string {
  const clean = id.toLowerCase().replace(/[^a-z0-9_]/g, '_');
  switch (dialect) {
    case 'mysql':
      return `\`${clean}\``;
    case 'postgres':
    case 'sqlite':
      return `"${clean}"`;
    case 'oracle':
      return `"${clean.toUpperCase()}"`;
  }
}

function formatDefaultValue(val: string): string {
  const v = val.trim();
  const upper = v.toUpperCase();
  if (['CURRENT_TIMESTAMP', 'NOW()', 'NULL', 'TRUE', 'FALSE', 'LOCALTIMESTAMP'].includes(upper) || /^-?\d+(\.\d+)?$/.test(v)) {
    return v;
  }
  if ((v.startsWith("'") && v.endsWith("'")) || (v.startsWith('"') && v.endsWith('"'))) {
    return v;
  }
  return `'${v.replace(/'/g, "''")}'`;
}

export function generateSqlDDL(
  nodes: DiagramNode[],
  edges: DiagramEdge[],
  dialect: SqlDialect = 'postgres'
): string {
  const tableNodes = nodes.filter(n => n.type === 'erd_table');
  if (tableNodes.length === 0) {
    return '-- No ERD tables found in this diagram.\n-- Add ERD Tables from the palette to generate SQL DDL.';
  }

  let sql = `-- ==========================================================\n`;
  sql += `-- Generated by Invisual Disparity (Visual Paradigm Engine)\n`;
  sql += `-- Dialect: ${dialect.toUpperCase()}\n`;
  sql += `-- Generated At: ${new Date().toISOString()}\n`;
  sql += `-- Total Tables: ${tableNodes.length}\n`;
  sql += `-- ==========================================================\n\n`;

  const mapType = (rawType: string, isPk: boolean, isCompositePk: boolean): string => {
    const t = rawType.trim().toUpperCase();

    if (dialect === 'postgres') {
      if (t === 'UUID') return 'UUID';
      if (t === 'BOOLEAN' || t === 'BOOL') return 'BOOLEAN';
      if (t === 'DATETIME' || t === 'TIMESTAMP') return 'TIMESTAMP WITH TIME ZONE';
      if (t === 'JSON') return 'JSONB';
      if (isPk && !isCompositePk && (t === 'SERIAL' || t === 'INT' || t === 'INTEGER')) return 'SERIAL PRIMARY KEY';
      if (isPk && !isCompositePk && t === 'BIGINT') return 'BIGSERIAL PRIMARY KEY';
      if (t === 'SERIAL') return 'INTEGER';
      return rawType;
    } else if (dialect === 'mysql') {
      if (t === 'UUID') return 'VARCHAR(36)';
      if (t === 'BOOLEAN' || t === 'BOOL') return 'BOOLEAN';
      if (t === 'DATETIME' || t === 'TIMESTAMP') return 'DATETIME';
      if (isPk && !isCompositePk && (t === 'INT' || t === 'INTEGER' || t === 'SERIAL')) return 'INT AUTO_INCREMENT PRIMARY KEY';
      if (isPk && !isCompositePk && t === 'BIGINT') return 'BIGINT AUTO_INCREMENT PRIMARY KEY';
      if (t === 'SERIAL') return 'INT UNSIGNED';
      return rawType;
    } else if (dialect === 'sqlite') {
      if (t === 'UUID') return 'TEXT';
      if (t === 'BOOLEAN' || t === 'BOOL') return 'INTEGER';
      if (t === 'DATETIME' || t === 'TIMESTAMP') return 'TEXT';
      if (t === 'JSON') return 'TEXT';
      if (isPk && !isCompositePk && (t === 'INT' || t === 'INTEGER' || t === 'SERIAL')) return 'INTEGER PRIMARY KEY AUTOINCREMENT';
      if (isPk && !isCompositePk) return `${rawType} PRIMARY KEY`;
      return rawType;
    } else {
      // Oracle
      if (t === 'UUID') return 'VARCHAR2(36)';
      if (t === 'BOOLEAN' || t === 'BOOL') return 'NUMBER(1)';
      if (t === 'DATETIME' || t === 'TIMESTAMP') return 'TIMESTAMP WITH TIME ZONE';
      if (t === 'TEXT') return 'CLOB';
      if (t === 'JSON') return 'CLOB';
      if (t === 'VARCHAR(255)') return 'VARCHAR2(255)';
      if (isPk && !isCompositePk && (t === 'INT' || t === 'INTEGER' || t === 'SERIAL')) {
        return 'NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
      }
      return rawType;
    }
  };

  const tableMap = new Map(tableNodes.map(t => [t.id, t]));
  const fkStatements: string[] = [];

  // Generate Table definitions
  for (const table of tableNodes) {
    const rawTableName = table.title.toLowerCase().replace(/[^a-z0-9_]/g, '_');
    const quotedTable = quoteIdentifier(rawTableName, dialect);

    sql += `-- Table: ${rawTableName}\n`;
    if (table.description) {
      sql += `-- Description: ${table.description}\n`;
    }

    if (dialect === 'postgres' || dialect === 'sqlite' || dialect === 'mysql') {
      sql += `CREATE TABLE IF NOT EXISTS ${quotedTable} (\n`;
    } else {
      sql += `CREATE TABLE ${quotedTable} (\n`;
    }

    const columnDefs: string[] = [];
    const cols = table.columns || [];
    const pkCols = cols.filter(c => c.isPk);
    const isCompositePk = pkCols.length > 1;

    for (const col of cols) {
      const rawColName = col.name.toLowerCase().replace(/[^a-z0-9_]/g, '_');
      const quotedCol = quoteIdentifier(rawColName, dialect);
      const typeDef = mapType(col.type || 'VARCHAR(255)', col.isPk, isCompositePk);

      let line = `    ${quotedCol.padEnd(24)} ${typeDef}`;

      // If single PK inlined already, don't duplicate constraints
      if (!typeDef.toUpperCase().includes('PRIMARY KEY')) {
        if (!col.isNullable) {
          line += ' NOT NULL';
        }
        if (col.isUnique && !col.isPk) {
          line += ' UNIQUE';
        }
        if (col.defaultValue !== undefined && col.defaultValue !== '') {
          line += ` DEFAULT ${formatDefaultValue(col.defaultValue)}`;
        }
      }

      columnDefs.push(line);
    }

    // Add composite PK constraint if multiple PKs exist
    if (isCompositePk) {
      const pkNames = pkCols.map(c => quoteIdentifier(c.name, dialect)).join(', ');
      columnDefs.push(`    CONSTRAINT ${quoteIdentifier(`pk_${rawTableName}`, dialect)} PRIMARY KEY (${pkNames})`);
    } else if (pkCols.length === 1 && !columnDefs.some(c => c.toUpperCase().includes('PRIMARY KEY'))) {
      const pkName = quoteIdentifier(pkCols[0].name, dialect);
      columnDefs.push(`    CONSTRAINT ${quoteIdentifier(`pk_${rawTableName}`, dialect)} PRIMARY KEY (${pkName})`);
    }

    // For SQLite: inline Foreign Key constraints inside CREATE TABLE
    if (dialect === 'sqlite') {
      for (const edge of edges) {
        if (
          edge.type === 'crows_foot_one_to_many' ||
          edge.type === 'crows_foot_one_to_one' ||
          edge.type === 'crows_foot_many_to_many'
        ) {
          // If this table is the target of the relationship
          if (edge.targetId === table.id) {
            const sourceTable = tableMap.get(edge.sourceId);
            if (sourceTable && sourceTable.id !== table.id) {
              const srcRawName = sourceTable.title.toLowerCase().replace(/[^a-z0-9_]/g, '_');
              const fkCol = table.columns?.find(c => c.isFk && c.name.toLowerCase().includes(srcRawName))
                || table.columns?.find(c => c.name.toLowerCase() === `${srcRawName}_id`)
                || { name: `${srcRawName}_id` };
              const pkCol = sourceTable.columns?.find(c => c.isPk) || { name: 'id' };

              const quotedSrc = quoteIdentifier(srcRawName, dialect);
              const quotedFkCol = quoteIdentifier(fkCol.name, dialect);
              const quotedPkCol = quoteIdentifier(pkCol.name, dialect);
              const quotedFkName = quoteIdentifier(`fk_${rawTableName}_${srcRawName}`, dialect);

              columnDefs.push(
                `    CONSTRAINT ${quotedFkName} FOREIGN KEY (${quotedFkCol}) REFERENCES ${quotedSrc}(${quotedPkCol}) ON DELETE CASCADE ON UPDATE CASCADE`
              );
            }
          }
        }
      }
    }

    sql += columnDefs.join(',\n');
    sql += `\n);\n\n`;
  }

  // Generate foreign key ALTER TABLE statements for Postgres, MySQL, Oracle
  if (dialect !== 'sqlite') {
    for (const edge of edges) {
      if (
        edge.type === 'crows_foot_one_to_many' ||
        edge.type === 'crows_foot_one_to_one' ||
        edge.type === 'crows_foot_many_to_many'
      ) {
        const sourceTable = tableMap.get(edge.sourceId);
        const targetTable = tableMap.get(edge.targetId);

        if (sourceTable && targetTable && sourceTable.id !== targetTable.id) {
          const srcRaw = sourceTable.title.toLowerCase().replace(/[^a-z0-9_]/g, '_');
          const tgtRaw = targetTable.title.toLowerCase().replace(/[^a-z0-9_]/g, '_');

          const fkCol = targetTable.columns?.find(c => c.isFk && c.name.toLowerCase().includes(srcRaw))
            || targetTable.columns?.find(c => c.name.toLowerCase() === `${srcRaw}_id`)
            || { name: `${srcRaw}_id` };
          const pkCol = sourceTable.columns?.find(c => c.isPk) || { name: 'id' };

          const qTgt = quoteIdentifier(tgtRaw, dialect);
          const qSrc = quoteIdentifier(srcRaw, dialect);
          const qFkCol = quoteIdentifier(fkCol.name, dialect);
          const qPkCol = quoteIdentifier(pkCol.name, dialect);
          const qFkName = quoteIdentifier(`fk_${tgtRaw}_${srcRaw}`, dialect);

          if (dialect === 'oracle') {
            fkStatements.push(
              `ALTER TABLE ${qTgt}\n  ADD CONSTRAINT ${qFkName}\n  FOREIGN KEY (${qFkCol}) REFERENCES ${qSrc}(${qPkCol})\n  ON DELETE CASCADE;`
            );
          } else {
            fkStatements.push(
              `ALTER TABLE ${qTgt}\n  ADD CONSTRAINT ${qFkName}\n  FOREIGN KEY (${qFkCol}) REFERENCES ${qSrc}(${qPkCol})\n  ON DELETE CASCADE ON UPDATE CASCADE;`
            );
          }
        }
      }
    }

    if (fkStatements.length > 0) {
      sql += `-- ==========================================================\n`;
      sql += `-- Foreign Key Constraints\n`;
      sql += `-- ==========================================================\n\n`;
      sql += fkStatements.join('\n\n') + '\n';
    }
  }

  return sql;
}
