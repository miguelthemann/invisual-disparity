import { DiagramNode, DiagramEdge } from '../types';

export type SqlDialect = 'postgres' | 'mysql' | 'sqlite' | 'oracle';

export function generateSqlDDL(
  nodes: DiagramNode[],
  edges: DiagramEdge[],
  dialect: SqlDialect = 'postgres'
): string {
  const tableNodes = nodes.filter(n => n.type === 'erd_table');
  if (tableNodes.length === 0) {
    return '-- No ERD tables found in this diagram.\n-- Add ERD Tables from the palette to generate SQL DDL.';
  }

  let sql = `-- ==========================================================\n`;
  sql += `-- Generated by Invisual Disparity (Architecture Engine)\n`;
  sql += `-- Dialect: ${dialect.toUpperCase()}\n`;
  sql += `-- Generated At: ${new Date().toISOString()}\n`;
  sql += `-- Total Tables: ${tableNodes.length}\n`;
  sql += `-- ==========================================================\n\n`;

  const mapType = (rawType: string, isPk: boolean): string => {
    const t = rawType.trim().toUpperCase();
    if (dialect === 'postgres') {
      if (isPk && (t === 'SERIAL' || t === 'INT' || t === 'INTEGER')) return 'SERIAL PRIMARY KEY';
      if (isPk && t === 'BIGINT') return 'BIGSERIAL PRIMARY KEY';
      if (t === 'DATETIME') return 'TIMESTAMP WITH TIME ZONE';
      if (t === 'JSON') return 'JSONB';
      return rawType;
    } else if (dialect === 'mysql') {
      if (isPk && (t === 'INT' || t === 'INTEGER')) return 'INT AUTO_INCREMENT PRIMARY KEY';
      if (isPk && t === 'BIGINT') return 'BIGINT AUTO_INCREMENT PRIMARY KEY';
      if (t === 'TEXT') return 'TEXT';
      return rawType;
    } else if (dialect === 'sqlite') {
      if (isPk && (t === 'INT' || t === 'INTEGER' || t === 'SERIAL')) return 'INTEGER PRIMARY KEY AUTOINCREMENT';
      return rawType;
    } else {
      // Oracle
      if (isPk && (t === 'INT' || t === 'INTEGER' || t === 'SERIAL')) return 'NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
      if (t === 'TEXT') return 'CLOB';
      if (t === 'VARCHAR(255)') return 'VARCHAR2(255)';
      return rawType;
    }
  };

  const fkStatements: string[] = [];

  // Generate Table definitions
  for (const table of tableNodes) {
    const tableName = table.title.toLowerCase().replace(/[^a-z0-9_]/g, '_');
    sql += `-- Table: ${tableName}\n`;
    if (table.description) {
      sql += `-- Description: ${table.description}\n`;
    }

    if (dialect === 'postgres' || dialect === 'sqlite' || dialect === 'mysql') {
      sql += `CREATE TABLE IF NOT EXISTS ${tableName} (\n`;
    } else {
      sql += `CREATE TABLE ${tableName} (\n`;
    }

    const columnDefs: string[] = [];
    const pkCols: string[] = [];
    const cols = table.columns || [];

    for (const col of cols) {
      const colName = col.name.toLowerCase().replace(/[^a-z0-9_]/g, '_');
      let typeDef = mapType(col.type || 'VARCHAR(255)', col.isPk);

      let line = `    ${colName.padEnd(20)} ${typeDef}`;
      
      // If typeDef already included PRIMARY KEY (like SERIAL PRIMARY KEY), don't duplicate
      if (!typeDef.toUpperCase().includes('PRIMARY KEY')) {
        if (!col.isNullable) {
          line += ' NOT NULL';
        }
        if (col.isUnique && !col.isPk) {
          line += ' UNIQUE';
        }
        if (col.defaultValue) {
          line += ` DEFAULT ${col.defaultValue}`;
        }
        if (col.isPk) {
          pkCols.push(colName);
        }
      }

      columnDefs.push(line);
    }

    // Add composite PK constraint if multiple or if not inlined
    if (pkCols.length > 0 && !columnDefs.some(c => c.includes('PRIMARY KEY'))) {
      columnDefs.push(`    CONSTRAINT pk_${tableName} PRIMARY KEY (${pkCols.join(', ')})`);
    }

    sql += columnDefs.join(',\n');
    sql += `\n);\n\n`;
  }

  // Generate foreign key relationships from edges
  const tableMap = new Map(tableNodes.map(t => [t.id, t]));
  for (const edge of edges) {
    if (
      edge.type === 'crows_foot_one_to_many' ||
      edge.type === 'crows_foot_one_to_one' ||
      edge.type === 'crows_foot_many_to_many'
    ) {
      const sourceTable = tableMap.get(edge.sourceId);
      const targetTable = tableMap.get(edge.targetId);

      if (sourceTable && targetTable && sourceTable.id !== targetTable.id) {
        const srcName = sourceTable.title.toLowerCase().replace(/[^a-z0-9_]/g, '_');
        const tgtName = targetTable.title.toLowerCase().replace(/[^a-z0-9_]/g, '_');

        const fkName = `fk_${tgtName}_${srcName}`;
        // Find if target table has an FK column referencing source table
        const fkCol = targetTable.columns?.find(c => c.isFk) || { name: `${srcName}_id` };
        const pkCol = sourceTable.columns?.find(c => c.isPk) || { name: 'id' };

        if (dialect !== 'sqlite') {
          fkStatements.push(
            `ALTER TABLE ${tgtName}\n  ADD CONSTRAINT ${fkName}\n  FOREIGN KEY (${fkCol.name}) REFERENCES ${srcName}(${pkCol.name})\n  ON DELETE CASCADE ON UPDATE CASCADE;`
          );
        }
      }
    }
  }

  if (fkStatements.length > 0) {
    sql += `-- ==========================================================\n`;
    sql += `-- Foreign Key Constraints\n`;
    sql += `-- ==========================================================\n\n`;
    sql += fkStatements.join('\n\n') + '\n';
  }

  return sql;
}
