import { DiagramNode, DiagramEdge, UMLAttribute, UMLMethod } from '../types';

export type TargetLanguage = 'typescript' | 'python' | 'java' | 'go' | 'csharp';

export function generateCode(
  nodes: DiagramNode[],
  edges: DiagramEdge[],
  language: TargetLanguage = 'typescript'
): string {
  const classNodes = nodes.filter(
    n => n.type === 'uml_class' || n.type === 'uml_interface' || n.type === 'uml_enum'
  );

  if (classNodes.length === 0) {
    return `// No UML Classes, Interfaces, or Enums found in this diagram.\n// Add UML elements to generate code.`;
  }

  switch (language) {
    case 'typescript':
      return generateTypeScript(classNodes, edges);
    case 'python':
      return generatePython(classNodes, edges);
    case 'java':
      return generateJava(classNodes, edges);
    case 'go':
      return generateGo(classNodes, edges);
    case 'csharp':
      return generateCSharp(classNodes, edges);
    default:
      return generateTypeScript(classNodes, edges);
  }
}

function cleanIdentifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '');
}

function capitalize(s: string): string {
  if (!s) return '';
  return s.charAt(0).toUpperCase() + s.slice(1);
}

// ---------------- TypeScript ----------------
function generateTypeScript(nodes: DiagramNode[], edges: DiagramEdge[]): string {
  let out = `/**\n * Generated by Invisual Disparity\n * Language: TypeScript / ECMAScript\n */\n\n`;

  const nodeMap = new Map(nodes.map(n => [n.id, n]));

  for (const node of nodes) {
    const className = cleanIdentifier(node.title);
    const isInterface = node.type === 'uml_interface' || node.stereotype?.toLowerCase().includes('interface');
    const isEnum = node.type === 'uml_enum' || node.stereotype?.toLowerCase().includes('enum');

    if (isEnum) {
      out += `export enum ${className} {\n`;
      const literals = node.enumLiterals || (node.attributes || []).map(a => a.name);
      if (literals.length > 0) {
        out += literals.map(l => `  ${cleanIdentifier(l)} = '${cleanIdentifier(l)}'`).join(',\n') + '\n';
      } else {
        out += `  DEFAULT = 'DEFAULT'\n`;
      }
      out += `}\n\n`;
      continue;
    }

    // Find inheritance & realizations
    const generalizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'generalization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    const realizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'realization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    let extendsClause = generalizations.length > 0 ? ` extends ${cleanIdentifier(generalizations[0])}` : '';
    let implementsClause = realizations.length > 0 ? ` implements ${realizations.map(cleanIdentifier).join(', ')}` : '';

    if (isInterface) {
      out += `export interface ${className}${extendsClause} {\n`;
      for (const attr of node.attributes || []) {
        out += `  ${attr.name}: ${mapTsType(attr.type)};\n`;
      }
      for (const m of node.methods || []) {
        out += `  ${m.name}(${m.parameters || ''}): ${mapTsType(m.returnType)};\n`;
      }
      out += `}\n\n`;
    } else {
      out += `export class ${className}${extendsClause}${implementsClause} {\n`;
      
      // Attributes
      for (const attr of node.attributes || []) {
        const vis = mapTsVisibility(attr.visibility);
        const def = attr.defaultValue ? ` = ${attr.defaultValue}` : '';
        out += `  ${vis} ${attr.name}: ${mapTsType(attr.type)}${def};\n`;
      }

      if ((node.attributes || []).length > 0) out += '\n';

      // Constructor
      if ((node.attributes || []).length > 0) {
        const params = (node.attributes || [])
          .map(a => `${a.name}: ${mapTsType(a.type)}`)
          .join(', ');

        out += `  constructor(${params}) {\n`;
        if (generalizations.length > 0) {
          out += `    super();\n`;
        }
        for (const attr of node.attributes || []) {
          out += `    this.${attr.name} = ${attr.name};\n`;
        }
        out += `  }\n\n`;
      }

      // Methods
      for (const m of node.methods || []) {
        const vis = mapTsVisibility(m.visibility);
        const isStatic = m.isStatic ? 'static ' : '';
        out += `  ${vis} ${isStatic}${m.name}(${m.parameters || ''}): ${mapTsType(m.returnType)} {\n`;
        out += `    // TODO: implement ${m.name}\n`;
        if (m.returnType && m.returnType.toLowerCase() !== 'void') {
          out += `    throw new Error('Method not implemented.');\n`;
        }
        out += `  }\n\n`;
      }

      out += `}\n\n`;
    }
  }

  return out;
}

function mapTsVisibility(v: string): string {
  switch (v) {
    case '+': return 'public';
    case '-': return 'private';
    case '#': return 'protected';
    default: return 'public';
  }
}

function mapTsType(t: string): string {
  if (!t) return 'any';
  const l = t.toLowerCase().trim();
  if (['int', 'integer', 'float', 'double', 'number'].includes(l)) return 'number';
  if (['str', 'string', 'text', 'varchar'].includes(l)) return 'string';
  if (['bool', 'boolean'].includes(l)) return 'boolean';
  if (['void'].includes(l)) return 'void';
  if (['date', 'datetime', 'timestamp'].includes(l)) return 'Date';
  if (l.endsWith('[]')) return `${mapTsType(t.slice(0, -2))}[]`;
  if (l.startsWith('list<') || l.startsWith('array<')) {
    const inner = t.slice(t.indexOf('<') + 1, -1);
    return `${mapTsType(inner)}[]`;
  }
  return cleanIdentifier(t);
}

// ---------------- Python ----------------
function generatePython(nodes: DiagramNode[], edges: DiagramEdge[]): string {
  let out = `"""\nGenerated by Invisual Disparity\nLanguage: Python 3.10+\n"""\nfrom typing import List, Optional, Any\nfrom dataclasses import dataclass\nfrom enum import Enum\n\n\n`;

  const nodeMap = new Map(nodes.map(n => [n.id, n]));

  for (const node of nodes) {
    const className = cleanIdentifier(node.title);
    const isEnum = node.type === 'uml_enum' || node.stereotype?.toLowerCase().includes('enum');

    if (isEnum) {
      out += `class ${className}(Enum):\n`;
      const literals = node.enumLiterals || (node.attributes || []).map(a => a.name);
      if (literals.length > 0) {
        for (const lit of literals) {
          out += `    ${cleanIdentifier(lit).toUpperCase()} = "${cleanIdentifier(lit)}"\n`;
        }
      } else {
        out += `    DEFAULT = "DEFAULT"\n`;
      }
      out += `\n\n`;
      continue;
    }

    const generalizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'generalization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    const baseClass = generalizations.length > 0 ? cleanIdentifier(generalizations[0]) : '';
    const classHeader = baseClass ? `class ${className}(${baseClass}):` : `class ${className}:`;

    out += `@dataclass\n${classHeader}\n`;
    if (node.description) {
      out += `    """${node.description}"""\n`;
    }

    const attrs = node.attributes || [];
    if (attrs.length === 0 && (node.methods || []).length === 0) {
      out += `    pass\n\n\n`;
      continue;
    }

    // Sort attributes: non-default fields first, default fields last (dataclass requirement)
    const nonDefaultAttrs = attrs.filter(a => !a.defaultValue);
    const defaultAttrs = attrs.filter(a => !!a.defaultValue);
    const sortedAttrs = [...nonDefaultAttrs, ...defaultAttrs];

    for (const attr of sortedAttrs) {
      const pyType = mapPyType(attr.type);
      if (attr.defaultValue) {
        let defVal = attr.defaultValue.trim();
        if (pyType === 'str' && !defVal.startsWith('"') && !defVal.startsWith("'")) {
          defVal = `"${defVal}"`;
        } else if (pyType === 'bool') {
          defVal = defVal.toLowerCase() === 'true' ? 'True' : 'False';
        }
        out += `    ${attr.name}: ${pyType} = ${defVal}\n`;
      } else {
        out += `    ${attr.name}: ${pyType}\n`;
      }
    }

    out += `\n`;

    for (const m of node.methods || []) {
      const isStatic = m.isStatic;
      if (isStatic) {
        out += `    @staticmethod\n`;
        out += `    def ${m.name}(${m.parameters || ''}) -> ${mapPyType(m.returnType)}:\n`;
      } else {
        const params = m.parameters ? `self, ${m.parameters}` : 'self';
        out += `    def ${m.name}(${params}) -> ${mapPyType(m.returnType)}:\n`;
      }
      out += `        """TODO: Implement ${m.name}"""\n`;
      out += `        raise NotImplementedError\n\n`;
    }

    out += `\n`;
  }

  return out;
}

function mapPyType(t: string): string {
  if (!t) return 'Any';
  const l = t.toLowerCase().trim();
  if (['int', 'integer'].includes(l)) return 'int';
  if (['float', 'double'].includes(l)) return 'float';
  if (['str', 'string', 'text', 'varchar'].includes(l)) return 'str';
  if (['bool', 'boolean'].includes(l)) return 'bool';
  if (['void', 'none'].includes(l)) return 'None';
  if (l.endsWith('[]')) return `List[${mapPyType(t.slice(0, -2))}]`;
  if (l.startsWith('list<') || l.startsWith('array<')) {
    const inner = t.slice(t.indexOf('<') + 1, -1);
    return `List[${mapPyType(inner)}]`;
  }
  return cleanIdentifier(t);
}

// ---------------- Java ----------------
function generateJava(nodes: DiagramNode[], edges: DiagramEdge[]): string {
  let out = `/**\n * Generated by Invisual Disparity\n * Language: Java\n */\npackage com.invisual.model;\n\nimport java.util.*;\n\n`;

  const nodeMap = new Map(nodes.map(n => [n.id, n]));

  for (const node of nodes) {
    const className = cleanIdentifier(node.title);
    const isInterface = node.type === 'uml_interface' || node.stereotype?.toLowerCase().includes('interface');
    const isEnum = node.type === 'uml_enum' || node.stereotype?.toLowerCase().includes('enum');

    if (isEnum) {
      out += `public enum ${className} {\n`;
      const literals = node.enumLiterals || (node.attributes || []).map(a => a.name);
      if (literals.length > 0) {
        out += literals.map(l => `    ${cleanIdentifier(l).toUpperCase()}`).join(',\n') + ';\n';
      } else {
        out += `    DEFAULT;\n`;
      }
      out += `}\n\n`;
      continue;
    }

    const generalizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'generalization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    const realizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'realization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    let extendsClause = generalizations.length > 0 ? ` extends ${cleanIdentifier(generalizations[0])}` : '';
    let implementsClause = realizations.length > 0 ? ` implements ${realizations.map(cleanIdentifier).join(', ')}` : '';

    if (isInterface) {
      out += `public interface ${className}${extendsClause} {\n`;
      for (const m of node.methods || []) {
        out += `    ${mapJavaType(m.returnType)} ${m.name}(${m.parameters || ''});\n`;
      }
      out += `}\n\n`;
    } else {
      out += `public class ${className}${extendsClause}${implementsClause} {\n`;
      for (const attr of node.attributes || []) {
        out += `    private ${mapJavaType(attr.type)} ${attr.name};\n`;
      }

      out += `\n    public ${className}() {}\n\n`;

      // Getters and Setters
      for (const attr of node.attributes || []) {
        const capitalized = attr.name.charAt(0).toUpperCase() + attr.name.slice(1);
        const jType = mapJavaType(attr.type);
        out += `    public ${jType} get${capitalized}() {\n        return this.${attr.name};\n    }\n\n`;
        out += `    public void set${capitalized}(${jType} ${attr.name}) {\n        this.${attr.name} = ${attr.name};\n    }\n\n`;
      }

      // Methods
      for (const m of node.methods || []) {
        out += `    public ${mapJavaType(m.returnType)} ${m.name}(${m.parameters || ''}) {\n`;
        out += `        // TODO: Implement method\n`;
        if (m.returnType && m.returnType.toLowerCase() !== 'void') {
          out += `        throw new UnsupportedOperationException("Not implemented yet.");\n`;
        }
        out += `    }\n\n`;
      }

      out += `}\n\n`;
    }
  }

  return out;
}

function mapJavaType(t: string): string {
  if (!t) return 'Object';
  const l = t.toLowerCase().trim();
  if (['int', 'integer'].includes(l)) return 'int';
  if (['float'].includes(l)) return 'float';
  if (['double'].includes(l)) return 'double';
  if (['str', 'string', 'text', 'varchar'].includes(l)) return 'String';
  if (['bool', 'boolean'].includes(l)) return 'boolean';
  if (['void'].includes(l)) return 'void';
  if (['date', 'datetime', 'timestamp'].includes(l)) return 'Date';
  if (l.endsWith('[]')) return `${mapJavaType(t.slice(0, -2))}[]`;
  if (l.startsWith('list<') || l.startsWith('array<')) {
    const inner = t.slice(t.indexOf('<') + 1, -1);
    return `List<${mapJavaType(inner)}>`;
  }
  return cleanIdentifier(t);
}

// ---------------- Go ----------------
function generateGo(nodes: DiagramNode[], edges: DiagramEdge[]): string {
  let out = `// Generated by Invisual Disparity\n// Language: Go\npackage model\n\nimport "time"\n\n`;

  const nodeMap = new Map(nodes.map(n => [n.id, n]));

  for (const node of nodes) {
    const className = cleanIdentifier(node.title);
    const isInterface = node.type === 'uml_interface' || node.stereotype?.toLowerCase().includes('interface');
    const isEnum = node.type === 'uml_enum' || node.stereotype?.toLowerCase().includes('enum');

    if (isEnum) {
      out += `type ${className} string\n\nconst (\n`;
      const literals = node.enumLiterals || (node.attributes || []).map(a => a.name);
      if (literals.length > 0) {
        for (const lit of literals) {
          const constName = `${className}${capitalize(cleanIdentifier(lit).toLowerCase())}`;
          out += `\t${constName} ${className} = "${cleanIdentifier(lit)}"\n`;
        }
      } else {
        out += `\t${className}Default ${className} = "DEFAULT"\n`;
      }
      out += `)\n\n`;
      continue;
    }

    const generalizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'generalization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    if (isInterface) {
      out += `type ${className} interface {\n`;
      for (const m of node.methods || []) {
        const ret = m.returnType && m.returnType.toLowerCase() !== 'void' ? ` ${mapGoType(m.returnType)}` : '';
        out += `\t${capitalize(m.name)}(${m.parameters || ''})${ret}\n`;
      }
      out += `}\n\n`;
    } else {
      out += `type ${className} struct {\n`;
      // Struct embedding for generalizations (inheritance in Go)
      for (const gen of generalizations) {
        out += `\t${cleanIdentifier(gen)}\n`;
      }
      for (const attr of node.attributes || []) {
        const fieldName = capitalize(attr.name);
        out += `\t${fieldName.padEnd(16)} ${mapGoType(attr.type).padEnd(12)} \`json:"${attr.name}"\`\n`;
      }
      out += `}\n\n`;

      for (const m of node.methods || []) {
        const receiver = className.charAt(0).toLowerCase();
        const ret = m.returnType && m.returnType.toLowerCase() !== 'void' ? ` ${mapGoType(m.returnType)}` : '';
        out += `func (${receiver} *${className}) ${capitalize(m.name)}(${m.parameters || ''})${ret} {\n`;
        out += `\t// TODO: implement\n`;
        if (ret) {
          out += `\tpanic("unimplemented")\n`;
        }
        out += `}\n\n`;
      }
    }
  }

  return out;
}

function mapGoType(t: string): string {
  if (!t) return 'any';
  const l = t.toLowerCase().trim();
  if (['int', 'integer'].includes(l)) return 'int';
  if (['float', 'double'].includes(l)) return 'float64';
  if (['str', 'string', 'text', 'varchar'].includes(l)) return 'string';
  if (['bool', 'boolean'].includes(l)) return 'bool';
  if (['void'].includes(l)) return '';
  if (['date', 'datetime', 'timestamp'].includes(l)) return 'time.Time';
  if (l.endsWith('[]')) return `[]${mapGoType(t.slice(0, -2))}`;
  if (l.startsWith('list<') || l.startsWith('array<')) {
    const inner = t.slice(t.indexOf('<') + 1, -1);
    return `[]${mapGoType(inner)}`;
  }
  return cleanIdentifier(t);
}

// ---------------- C# ----------------
function generateCSharp(nodes: DiagramNode[], edges: DiagramEdge[]): string {
  let out = `// Generated by Invisual Disparity\n// Language: C# / .NET\nnamespace Invisual.Model;\n\nusing System;\nusing System.Collections.Generic;\n\n`;

  const nodeMap = new Map(nodes.map(n => [n.id, n]));

  for (const node of nodes) {
    const className = cleanIdentifier(node.title);
    const isInterface = node.type === 'uml_interface' || node.stereotype?.toLowerCase().includes('interface');
    const isEnum = node.type === 'uml_enum' || node.stereotype?.toLowerCase().includes('enum');

    if (isEnum) {
      out += `public enum ${className}\n{\n`;
      const literals = node.enumLiterals || (node.attributes || []).map(a => a.name);
      if (literals.length > 0) {
        out += literals.map(l => `    ${capitalize(cleanIdentifier(l))}`).join(',\n') + '\n';
      } else {
        out += `    Default\n`;
      }
      out += `}\n\n`;
      continue;
    }

    const generalizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'generalization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    const realizations = edges
      .filter(e => e.sourceId === node.id && e.type === 'realization')
      .map(e => nodeMap.get(e.targetId)?.title)
      .filter(Boolean) as string[];

    const inherits = [...generalizations, ...realizations].map(cleanIdentifier);
    const inheritClause = inherits.length > 0 ? ` : ${inherits.join(', ')}` : '';

    if (isInterface) {
      out += `public interface ${className}${inheritClause}\n{\n`;
      for (const m of node.methods || []) {
        out += `    ${mapCSharpType(m.returnType)} ${capitalize(m.name)}(${m.parameters || ''});\n`;
      }
      out += `}\n\n`;
    } else {
      out += `public class ${className}${inheritClause}\n{\n`;
      for (const attr of node.attributes || []) {
        out += `    public ${mapCSharpType(attr.type)} ${capitalize(attr.name)} { get; set; }\n`;
      }
      out += `\n`;
      for (const m of node.methods || []) {
        out += `    public ${mapCSharpType(m.returnType)} ${capitalize(m.name)}(${m.parameters || ''})\n    {\n        throw new NotImplementedException();\n    }\n\n`;
      }
      out += `}\n\n`;
    }
  }

  return out;
}

function mapCSharpType(t: string): string {
  if (!t) return 'object';
  const l = t.toLowerCase().trim();
  if (['int', 'integer'].includes(l)) return 'int';
  if (['float'].includes(l)) return 'float';
  if (['double'].includes(l)) return 'double';
  if (['str', 'string', 'text', 'varchar'].includes(l)) return 'string';
  if (['bool', 'boolean'].includes(l)) return 'bool';
  if (['void'].includes(l)) return 'void';
  if (['date', 'datetime', 'timestamp'].includes(l)) return 'DateTime';
  if (l.endsWith('[]')) return `List<${mapCSharpType(t.slice(0, -2))}>`;
  if (l.startsWith('list<') || l.startsWith('array<')) {
    const inner = t.slice(t.indexOf('<') + 1, -1);
    return `List<${mapCSharpType(inner)}>`;
  }
  return cleanIdentifier(t);
}
